    std::vector<double> ScaleCoefficients(const std::vector<double> &coefficients,
                                          double scale)
    {
      std::vector<double> scaled = coefficients;
      for (double &coeff : scaled)
      {
        coeff *= scale;
      }
      return scaled;
    }

